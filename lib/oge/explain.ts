/** Накладывает разбор на вариант из сборника и помечает его как разобранный */
export function withExplanations(base: OgeVariant, data: ExplainedData): OgeVariant {
  const { listening, reading, grammar, writing, speaking } = base;

  const choice = <T extends { n: number; explanation: Explanation }>(items: T[]) =>
    items.map((item) => ({ ...item, explanation: data.choice[item.n] ?? item.explanation }));

  return {
    ...base,
    subtitle: data.subtitle,
    origin: { synthAudio: base.origin?.synthAudio ?? false, explained: true },
    rules: data.rules,
    listening: {
      ...listening,
      part1: { ...listening.part1, questions: choice(listening.part1.questions), strategy: STRATEGIES.part1 },
      part5: {
        ...listening.part5,
        explanations: { ...listening.part5.explanations, ...data.matching5 },
        strategy: STRATEGIES.part5,
      },
      part6: {
        ...listening.part6,
        rows: listening.part6.rows.map((row) => ({ ...row, explanation: data.rows[row.n] ?? row.explanation })),
        strategy: STRATEGIES.part6,
      },
    },
    reading: {
      part12: {
        ...reading.part12,
        explanations: { ...reading.part12.explanations, ...data.matching12 },
        strategy: STRATEGIES.part12,
      },
      part13: { ...reading.part13, statements: choice(reading.part13.statements), strategy: STRATEGIES.part13 },
    },
    grammar: {
      part20: {
        ...grammar.part20,
        lines: grammar.part20.lines.map((line) =>
          "n" in line ? { ...line, explanation: data.gaps[line.n] ?? line.explanation } : line,
        ),
        strategy: STRATEGIES.part20,
      },
      part29: {
        ...grammar.part29,
        lines: grammar.part29.lines.map((line) =>
          "n" in line ? { ...line, explanation: data.gaps[line.n] ?? line.explanation } : line,
        ),
        strategy: STRATEGIES.part29,
      },
    },
    writing: {
      ...writing,
      sample: data.writing.sample,
      templateSample: data.writing.templateSample,
      strategy: STRATEGIES.writing,
    },
    speaking: {
      ...speaking,
      task1: { ...speaking.task1, hardWords: data.speaking.hardWords, strategy: STRATEGIES.task1 },
      task2: {
        ...speaking.task2,
        questions: speaking.task2.questions.map((question, index) => ({
          ...question,
          sample: data.speaking.task2Samples[index] ?? question.sample,
        })),
        strategy: STRATEGIES.task2,
      },
      task3: { ...speaking.task3, sample: data.speaking.task3Sample, strategy: STRATEGIES.task3 },
    },
  };
}
